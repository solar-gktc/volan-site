"""Assemble gc-volan-1/anasayfa-v2.html from the section fragments.

Shell parts (menu, quick-contact fab) are copied from index.html between their comment markers,
so the new page keeps the site's shared chrome. Run from anywhere:
    python3 .impeccable/mocks/anasayfa-v2/_kit/assemble.py
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[4]          # gc-volan-1/
MOCKS = ROOT / '.impeccable/mocks/anasayfa-v2'
ORDER = ['hero', 'hizmetler', 'kampanya', 'kalite', 'marka', 'istatistik', 'tesis', 'yorumlar', 'miras', 'final']

index = (ROOT / 'index.html').read_text()


def between(start, end):
    m = re.search(re.escape(start) + r'.*?' + re.escape(end), index, re.S)
    if not m:
        raise SystemExit(f'marker not found in index.html: {start}')
    return m.group(0)


menu = between('<!-- menu -->', '<!-- /menu -->')
fab = between('<!-- fab:', '<!-- /fab -->')

css = '\n'.join(f'<link rel="stylesheet" href="assets/css/anasayfa/{s}.css">'
                for s in ORDER if (ROOT / f'assets/css/anasayfa/{s}.css').exists())
js = '\n'.join(f'<script type="module" src="assets/js/anasayfa/{s}.js"></script>'
               for s in ORDER if (ROOT / f'assets/js/anasayfa/{s}.js').exists())

sections = []
for s in ORDER:
    frag = MOCKS / s / 'fragment.html'
    if not frag.exists():
        raise SystemExit(f'missing fragment: {frag}')
    sections.append(frag.read_text().strip())

